"""Prepare the pinned base/base sources used by the scoped head-listener workspace.

Usage: python3 -I tools/prepare-upstream.py <base-5476069f.tar.gz>

Verifies the tarball sha256, extracts only the nine crates in the
`base-consensus-gossip` dependency closure into upstream/base-<commit>/ with
their manifests unmodified, and derives two manifests from the upstream root
Cargo.toml: a vendor mini workspace (so the crates inherit workspace fields)
and the head-listener root workspace, which excludes upstream/ so the vendored
crates are non-members and only their activated features are resolved (no
optional reth dependencies). Re-running is idempotent; it refuses an unexpected tarball.
"""

import hashlib
import json
import pathlib
import shutil
import sys
import tarfile

COMMIT = "5476069f1eb74a56bccb56fdefd4b4bb0e3cda42"
TARBALL_SHA256 = "9784e20a3cfeac555d96e8d1f15526d5264f0e6d8885b951c6f1220355038012"
TARBALL_URL = f"https://codeload.github.com/base/base/tar.gz/{COMMIT}"
CRATES = {
    "base-consensus-gossip": "crates/consensus/gossip",
    "base-consensus-peers": "crates/consensus/peers",
    "base-consensus-disc": "crates/consensus/disc",
    "base-protocol": "crates/consensus/protocol",
    "base-common-chains": "crates/common/chains",
    "base-common-genesis": "crates/common/genesis",
    "base-common-consensus": "crates/common/consensus",
    "base-common-rpc-types-engine": "crates/common/rpc-types-engine",
    "base-metrics": "crates/utilities/metrics",
}
ROOT_FILES = ["Cargo.toml", "Cargo.lock", "rust-toolchain.toml", "LICENSE"]
HERE = pathlib.Path(__file__).resolve().parent.parent
DEST = HERE / "upstream" / f"base-{COMMIT[:8]}"
PREFIX = f"base-{COMMIT}/"


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def wanted(rel):
    if rel in ROOT_FILES:
        return True
    return any(rel == d or rel.startswith(d + "/") for d in CRATES.values())


def extract(tarball):
    if DEST.exists():
        shutil.rmtree(DEST)
    DEST.mkdir(parents=True)
    count = 0
    with tarfile.open(tarball, "r:gz") as tar:
        for m in tar:
            if m.name == PREFIX.rstrip("/") and m.isdir():
                continue
            if not m.name.startswith(PREFIX):
                raise SystemExit(f"unexpected member {m.name!r}")
            rel = m.name[len(PREFIX):]
            if not rel or not wanted(rel) or m.isdir():
                continue
            if not m.isfile() or rel.startswith("/") or ".." in pathlib.PurePosixPath(rel).parts:
                raise SystemExit(f"refusing non-regular or unsafe member {m.name!r}")
            out = DEST / rel
            out.parent.mkdir(parents=True, exist_ok=True)
            with tar.extractfile(m) as src, open(out, "xb") as dst:
                shutil.copyfileobj(src, dst)
            count += 1
    return count


def workspace_manifest(kind):
    """kind="root": head-listener workspace; kind="vendor": mini workspace for the vendored crates."""
    src = (DEST / "Cargo.toml.upstream").read_text().splitlines()
    vendored = set(CRATES.values())
    out, section, skip = [], None, False
    for line in src:
        stripped = line.strip()
        if stripped.startswith("[") and stripped.endswith("]"):
            section = stripped
            skip = section in ("[workspace]", "[workspace.metadata.cargo-udeps.ignore]")
            if section == "[workspace]":
                if kind == "root":
                    members = '["crates/enclave-base-head-listener"]\nexclude = ["upstream"]'
                else:
                    members = "[" + ", ".join(f'"{p}"' for p in sorted(vendored)) + "]"
                out += ["[workspace]", 'resolver = "2"', f"members = {members}", ""]
                continue
        if skip:
            continue
        if section == "[workspace.dependencies]" and 'path = "' in line:
            path = line.split('path = "', 1)[1].split('"', 1)[0]
            # The vendor workspace keeps every entry: cargo parses inherited dev-dependencies
            # even though it never loads them for non-member packages.
            if path not in vendored and kind == "root":
                continue
            if kind == "root":
                line = line.replace(f'path = "{path}"', f'path = "upstream/base-{COMMIT[:8]}/{path}"')
        out.append(line)
    header = [
        "# GENERATED by tools/prepare-upstream.py from base/base "
        f"{COMMIT} Cargo.toml.",
        "# Scoped workspace: only the base-consensus-gossip closure is vendored." if kind == "root"
        else "# Vendored mini workspace: the nine crates resolve inheritance here, as non-members of the root.",
        "",
    ]
    return "\n".join(header + out) + "\n"


def main():
    tarball = pathlib.Path(sys.argv[1])
    digest = sha256(tarball)
    if digest != TARBALL_SHA256:
        raise SystemExit(f"tarball sha256 {digest} != pinned {TARBALL_SHA256}")
    files = extract(tarball)
    (DEST / "Cargo.toml").rename(DEST / "Cargo.toml.upstream")
    (DEST / "Cargo.toml").write_text(workspace_manifest("vendor"))
    (HERE / "Cargo.toml").write_text(workspace_manifest("root"))
    shutil.copyfile(DEST / "rust-toolchain.toml", HERE / "rust-toolchain.toml")
    record = {
        "source": TARBALL_URL,
        "commit": COMMIT,
        "tarballSha256": digest,
        "filesExtracted": files,
        "crates": CRATES,
        "crateManifestsModified": False,
        "generated": ["Cargo.toml (root)", f"upstream/base-{COMMIT[:8]}/Cargo.toml (vendor mini workspace)"],
    }
    (HERE / "upstream" / "PROVENANCE.json").write_text(json.dumps(record, indent=2) + "\n")
    print(json.dumps(record, indent=2))


if __name__ == "__main__":
    main()
