"""Bridge tests with real sockets: the inside Bridge (loopback TCP -> AF_UNIX) and the outside Bridge (AF_UNIX -> TCP)
of runner.py relay between real clients and real "host" servers. Run by run-tests.sh INSIDE `unshare -rn` (loopback
only; 203.0.113.5 carries the inside listeners as in a restore namespace, 127.0.0.3 the hosts). No mocks: every byte
goes through the kernel, and every assertion is about what a client or a host actually received."""
