INSIDE_IP, HOST_IP = '203.0.113.5', '127.0.0.3'
BLOCK = hashlib.shake_256(b'bridge-test').digest(1 << 20)


def pieces(seed, n):
    """n generated bytes in 64 KiB pieces, different per seed and position."""
    i = 0
    while n > 0:
        off = (seed * 7919 + i * 104729) % (len(BLOCK) - 65536)
        p = (struct.pack('>QQ', seed, i) + BLOCK[off:off + 65520])[:n]
        yield p
        n -= len(p)
        i += 1


def data(seed, n):
    return b''.join(pieces(seed, n))


def send_stream(c, seed, n):
    for p in pieces(seed, n):
        c.sendall(p)


def digest(seed, n):
    h = hashlib.sha256()
    for p in pieces(seed, n):
        h.update(p)
    return h.digest()


def recv_all(s, limit=1 << 30):
    out = bytearray()
    while len(out) < limit:
        d = s.recv(1 << 16)
        if not d:
            break
        out += d
    return bytes(out)


def rss_anon_kib():
    for line in open('/proc/self/status'):
        if line.startswith('RssAnon:'):
            return int(line.split()[1])
    return 0


def fds():
    return len(os.listdir('/proc/self/fd'))


class Host:
    """A real TCP server on HOST_IP; handler(conn) runs in its own thread per accepted connection."""
    def __init__(self, handler, backlog=64, inline=False):
        self.s = socket.socket()
        self.s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        self.s.bind((HOST_IP, 0))
        self.s.listen(backlog)
        self.addr = self.s.getsockname()
        self.accepted, self.threads, self.errors = 0, [], []
        self.handler, self.inline = handler, inline
        self.release = threading.Event()  # handlers that hold a connection open wait on it
        if handler:
            threading.Thread(target=self._loop, daemon=True).start()

    def _loop(self):
        while True:
            try:
                c, _ = self.s.accept()
            except OSError:
                return
            self.accepted += 1
            if self.inline:
                self._one(c)
                continue
            t = threading.Thread(target=self._one, args=(c,), daemon=True)
            self.threads.append(t)
            t.start()

    def _one(self, c):
        try:
            self.handler(c)
        except OSError as e:
            self.errors.append(type(e).__name__)
        finally:
            c.close()

    def close(self):
        self.release.set()
        try:
            self.s.shutdown(socket.SHUT_RDWR)
        except OSError:
            pass
        self.s.close()


class Pair:
    """inside Bridge on INSIDE_IP:port -> AF_UNIX path -> outside Bridge -> host."""
    def __init__(self, host_addr, endpoints=1, outside=None, **cfg):
        """cfg: settings of both ends; outside: further settings for the outside end only."""
        self.cfg = runner.bridge_settings({'bridge': cfg})
        self.dir = tempfile.mkdtemp(prefix='brt-', dir='/tmp')
        self.outside = runner.Bridge(True, runner.bridge_settings({'bridge': dict(cfg, **(outside or {}))}))
        self.inside = runner.Bridge(False, self.cfg)
        self.addrs = []
        for i in range(endpoints):
            path = os.path.join(self.dir, str(i))
            u = socket.socket(socket.AF_UNIX)
            u.bind(path)
            u.listen(128)
            self.outside.add(u, host_addr)
            t = socket.socket()
            t.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
            t.bind((INSIDE_IP, 0))
            t.listen(128)
            self.addrs.append(t.getsockname())
            self.inside.add(t, path)
        self.outside.start()
        self.inside.start()
        self.stopped = None

    def connect(self, i=0, timeout=30):
        return socket.create_connection(self.addrs[i], timeout)

    def live(self):
        return len(self.inside.conns), len(self.outside.conns)

    def wait_live(self, want, secs=10):
        end = time.monotonic() + secs
        while time.monotonic() < end and self.live() != want:
            time.sleep(0.05)
        return self.live()

    def stop(self):
        if self.stopped is None:
            self.stopped = (self.inside.stop(), self.outside.stop())
            shutil.rmtree(self.dir, ignore_errors=True)
        return self.stopped


class BridgeTest(unittest.TestCase):
    def setUp(self):
        gc.collect()
        self.fd0, self.threads0 = fds(), set(threading.enumerate())
        self.cleanup = []

    def tearDown(self):
        for f in reversed(self.cleanup):
            f()

    def pair(self, host, **kw):
        p = Pair(host.addr, **kw)
        self.cleanup.append(p.stop)
        return p

    def host(self, handler, **kw):
        h = Host(handler, **kw)
        self.cleanup.append(h.close)
        return h

    def assert_clean_stop(self, p, *hosts):
        si, so = p.stop()
        for st in (si, so):
            self.assertIsNone(st['loopError'])
            self.assertTrue(st['threadEnded'])
        for h in hosts:
            h.close()
            for t in h.threads:
                t.join(10)
        time.sleep(0.2)
        gc.collect()
        self.assertEqual(set(threading.enumerate()) - self.threads0, set(), 'no bridge or host thread outlives the test')
        self.assertLessEqual(fds(), self.fd0, 'every bridge, host and client descriptor is closed')
        return si, so

    # -- byte-exactness, concurrency, backpressure --
    def test_concurrent_bidirectional_streams_are_byte_exact(self):
        def echo_digest(c):  # host: read the request, answer it with generated data, then echo the upload's digest
            n, seed, up = struct.unpack('>QQQ', recv_exactly(c, 24))
            send_stream(c, seed, n)
            h, left = hashlib.sha256(), up
            while left:
                d = c.recv(min(left, 1 << 16))
                if not d:
                    return
                h.update(d)
                left -= len(d)
            c.sendall(h.digest())
        host = self.host(echo_digest)
        p = self.pair(host, endpoints=4)
        results, errors = {}, []

        def client(k):
            try:
                n, up = (3 << 20) + k * 4099, (1 << 20) + k * 7
                s = p.connect(k % 4)
                s.sendall(struct.pack('>QQQ', n, k, up))
                w = threading.Thread(target=send_stream, args=(s, 10_000 + k, up))  # upload while the download flows
                w.start()
                h, left = hashlib.sha256(), n
                while left:
                    d = s.recv(min(left, 1 << 16))
                    if not d:
                        raise ConnectionAbortedError('eof with %d left' % left)
                    h.update(d)
                    left -= len(d)
                echoed = recv_exactly(s, 32)
                w.join()
                s.close()
                results[k] = (h.digest() == digest(k, n), echoed == digest(10_000 + k, up))
            except OSError as e:
                errors.append(repr(e))
        ts = [threading.Thread(target=client, args=(k,)) for k in range(24)]
        for t in ts:
            t.start()
        for t in ts:
            t.join(120)
        self.assertEqual(errors, [])
        self.assertEqual(results, {k: (True, True) for k in range(24)})
        self.assertEqual(p.wait_live((0, 0)), (0, 0))
        si, so = self.assert_clean_stop(p, host)
        self.assertEqual(host.accepted, 24, 'every client reached the real host')
        self.assertEqual((si['relayed'], so['relayed']), (24, 24))
        self.assertLessEqual(si['buffersAllocated'], 2 * 24)

    def test_slow_reader_backpressure_holds_one_chunk_per_direction(self):
        n = 48 << 20
        host = self.host(lambda c: send_stream(c, 7, n))
        p = self.pair(host)
        s = p.connect()
        s.setsockopt(socket.SOL_SOCKET, socket.SO_RCVBUF, 64 << 10)
        time.sleep(1.5)  # the client reads nothing: the host must be held back, not buffered here
        anon_stalled = rss_anon_kib()
        self.assertEqual(p.inside.buffers + p.outside.buffers, 2, 'one waiting chunk at each end, nothing more')
        h, got = hashlib.sha256(), 0
        while True:
            d = s.recv(1 << 15)
            if not d:
                break
            h.update(d)
            got += len(d)
            if got < (8 << 20):
                time.sleep(0.0005)  # a slow consumer for the first part
        s.close()
        self.assertEqual((got, h.digest()), (n, digest(7, n)))
        self.assertLess(anon_stalled - self.anon0, 16 << 10, 'a stalled 48 MiB transfer costs no buffering here')
        self.assert_clean_stop(p, host)

    def test_long_trickle_is_not_cut_by_idle_or_age(self):
        def trickle(c):
            for i in range(14):
                c.sendall(data(i, 4096))
                time.sleep(0.5)  # 7 s in total, longer than every timeout below; never 1 s without a byte
        host = self.host(trickle)
        p = self.pair(host, idleSecs=1, halfClosedIdleSecs=1, stalledSendSecs=1)
        s = p.connect()
        got = recv_all(s)
        s.close()
        self.assertEqual(got, b''.join(data(i, 4096) for i in range(14)))
        si, so = self.assert_clean_stop(p, host)
        self.assertEqual(si['idleTimeouts'] + so['idleTimeouts'] + si['stalledTimeouts'] + so['stalledTimeouts'], 0)

    # -- half-close, both directions --
    def test_client_half_close_reaches_host_and_response_flows_back(self):
        def answer_after_eof(c):
            body = recv_all(c)
            c.sendall(hashlib.sha256(body).digest() + data(3, 5 << 20))
        host = self.host(answer_after_eof)
        p = self.pair(host)
        s = p.connect()
        payload = data(2, 3 << 20)
        s.sendall(payload)
        s.shutdown(socket.SHUT_WR)
        got = recv_all(s)
        s.close()
        self.assertEqual(got[:32], hashlib.sha256(payload).digest(), 'the host saw the upload end exactly once')
        self.assertEqual(got[32:], data(3, 5 << 20))
        self.assertEqual(p.wait_live((0, 0)), (0, 0))
        self.assert_clean_stop(p, host)

    def test_host_half_close_keeps_client_to_host_direction_open(self):
        seen = {}

        def respond_then_listen(c):
            c.sendall(data(5, 1 << 20))
            c.shutdown(socket.SHUT_WR)
            seen['afterEof'] = recv_all(c)
        host = self.host(respond_then_listen)
        p = self.pair(host)
        s = p.connect()
        self.assertEqual(recv_all(s), data(5, 1 << 20))
        s.sendall(b'still talking after your EOF')
        s.shutdown(socket.SHUT_WR)
        self.assertEqual(p.wait_live((0, 0)), (0, 0))
        s.close()
        host.threads[0].join(10)
        self.assertEqual(seen['afterEof'], b'still talking after your EOF')
        self.assert_clean_stop(p, host)

    # -- rejection, status byte, real-host positive control --
    def test_down_host_is_refused_and_probe_requires_the_real_host(self):
        down = Host(None)
        down.close()  # nothing listens there now
        p = Pair(down.addr)
        self.cleanup.append(p.stop)
        s = p.connect()
        s.settimeout(10)
        try:
            self.assertEqual(s.recv(1), b'', 'no byte, no fake host')
        except ConnectionResetError:
            pass
        s.close()
        with self.assertRaises(OSError):
            runner.bridged(os.path.join(p.dir, '0'))
        si, so = self.assert_clean_stop(p)
        self.assertEqual(so['dialFailed'], 2)
        self.assertEqual(si['statusFailed'], 1)
        up = self.host(lambda c: c.recv(1))
        p2 = self.pair(up)
        runner.bridged(os.path.join(p2.dir, '0')).close()
        for _ in range(100):
            if up.accepted:
                break
            time.sleep(0.05)
        self.assertEqual(up.accepted, 1, 'the positive control is the real host accepting, not the bridge')
        self.assert_clean_stop(p2, up)

    def test_connect_timeout_refuses_without_leaking(self):
        host = Host(None, backlog=0)  # never accepts: once its queue is full, SYNs are dropped and dials hang
        self.cleanup.append(host.close)
        fill = []
        for _ in range(4):
            f = socket.socket()
            f.setblocking(False)
            f.connect_ex(host.addr)
            fill.append(f)
        time.sleep(0.3)
        p = self.pair(host, connectSecs=1, statusSecs=3)
        t0 = time.monotonic()
        s = p.connect()
        s.settimeout(10)
        try:
            got = s.recv(1)
        except ConnectionResetError:
            got = b''
        s.close()
        took = time.monotonic() - t0
        self.assertEqual(got, b'')
        self.assertLess(took, 3, 'refused at the connect timeout, not at the status timeout')
        for f in fill:
            f.close()
        si, so = self.assert_clean_stop(p, host)
        self.assertEqual(so['connectTimeouts'] + so['dialFailed'], 1)

    # -- malicious or dead peers: stalled, idle; limits --
    def test_stalled_reader_is_closed_and_frees_its_buffers(self):
        host = self.host(lambda c: send_stream(c, 9, 256 << 20))
        p = self.pair(host, stalledSendSecs=2)
        s = p.connect()
        s.setsockopt(socket.SOL_SOCKET, socket.SO_RCVBUF, 64 << 10)
        self.assertEqual(p.wait_live((1, 1)), (1, 1))
        self.assertEqual(p.wait_live((0, 0), secs=15), (0, 0), 'a reader that never reads is dropped')
        self.assertEqual((len(p.inside.pool), len(p.outside.pool)), (p.inside.buffers, p.outside.buffers), 'chunks returned')
        s.close()
        si, so = self.assert_clean_stop(p, host)
        self.assertGreaterEqual(si['stalledTimeouts'] + so['stalledTimeouts'], 1, (si, so))

    def test_idle_and_half_closed_idle_connections_end(self):
        host = self.host(lambda c: (recv_all(c), host.release.wait(30)))
        p = self.pair(host, idleSecs=2, halfClosedIdleSecs=1)
        idle = p.connect()
        half = p.connect()
        half.shutdown(socket.SHUT_WR)  # the host never answers nor closes: a half-closed connection that never ends
        self.assertEqual(p.wait_live((2, 2)), (2, 2))
        self.assertEqual(p.wait_live((0, 0), secs=10), (0, 0))
        idle.close()
        half.close()
        si, so = self.assert_clean_stop(p, host)
        self.assertGreaterEqual(si['idleTimeouts'] + so['idleTimeouts'], 1)
        self.assertGreaterEqual(si['halfClosedTimeouts'] + so['halfClosedTimeouts'], 1)

    def capacity_case(self, end, cap):
        """`cap` long downloads fill one end's per-endpoint or global cap; each client sent its request then
        shutdown(SHUT_WR) and keeps receiving a paced 16 MiB response. A newcomer is refused with no byte and never
        reaches the host; every long response arrives complete and byte-exact (no eviction, no timeout); afterwards the
        freed capacity serves a new connection in full."""
        n = 16 << 20

        def long_after_eof(c):
            seed = int(recv_all(c))
            for piece in pieces(seed, n):
                c.sendall(piece)
                time.sleep(0.004)  # about 4 s per response
        host = self.host(long_after_eof)
        limits = {'per-endpoint': {'maxConnsPerEndpoint': 2}, 'global': {'maxConns': 2}}[cap]
        loose = {'maxConnsPerEndpoint': 64, 'maxConns': 64}
        cfg, out = (dict(loose, **limits), loose) if end == 'inside' else (loose, limits)
        p = self.pair(host, endpoints=2, outside=out, halfClosedIdleSecs=1, idleSecs=2, stalledSendSecs=2, **cfg)
        firsts = [0, 0] if cap == 'per-endpoint' else [0, 1]
        newcomer_ep = 0 if cap == 'per-endpoint' else 1
        longs = []
        for k, ep in enumerate(firsts):
            s = p.connect(ep)
            s.sendall(b'%d' % (100 + k))
            s.shutdown(socket.SHUT_WR)
            longs.append(s)
        self.assertEqual(p.wait_live((2, 2)), (2, 2))
        heads = [recv_exactly(s, 1 << 20) for s in longs]  # both responses are flowing
        accepted = host.accepted
        newcomer = p.connect(newcomer_ep)
        newcomer.settimeout(10)
        try:
            got = newcomer.recv(1)
        except ConnectionResetError:
            got = b''
        newcomer.close()
        self.assertEqual(got, b'', 'the newcomer is refused')
        self.assertEqual(host.accepted, accepted, 'the refused newcomer never reached the host')
        for k, (s, head) in enumerate(zip(longs, heads)):
            h = hashlib.sha256(head)
            while True:
                d = s.recv(1 << 16)
                if not d:
                    break
                h.update(d)
            s.close()
            self.assertEqual(h.digest(), digest(100 + k, n), 'half-closed response %d complete and byte-exact' % k)
        self.assertEqual(p.wait_live((0, 0)), (0, 0))
        again = p.connect(newcomer_ep)
        again.sendall(b'7')
        again.shutdown(socket.SHUT_WR)
        h = hashlib.sha256()
        while True:
            d = again.recv(1 << 16)
            if not d:
                break
            h.update(d)
        again.close()
        self.assertEqual(h.digest(), digest(7, n), 'freed capacity serves the next connection')
        si, so = self.assert_clean_stop(p, host)
        capped = si if end == 'inside' else so
        self.assertEqual(capped['rejectedEndpointLimit' if cap == 'per-endpoint' else 'rejectedLimit'], 1, (si, so))
        if end == 'outside':
            self.assertEqual(si['statusFailed'], 1, 'the inside saw status 2 and refused its client')
        for st in (si, so):
            self.assertEqual((st['halfClosedTimeouts'], st['idleTimeouts'], st['stalledTimeouts'], st['resets']), (0, 0, 0, 0), st)
        self.assertEqual((si['closedClean'], so['closedClean']), (3, 3))

    def test_paused_reader_of_half_closed_response_is_held_by_the_stall_deadline_only(self):
        n = 24 << 20

        def answer(c):
            seed = int(recv_all(c))
            send_stream(c, seed, n)
        host = self.host(answer)
        p = self.pair(host, halfClosedIdleSecs=1, idleSecs=1, stalledSendSecs=8)
        s = p.connect()
        s.setsockopt(socket.SOL_SOCKET, socket.SO_RCVBUF, 64 << 10)
        s.sendall(b'11')
        s.shutdown(socket.SHUT_WR)
        head = recv_exactly(s, 1 << 16)
        time.sleep(3.5)  # backpressured, nothing moves: longer than the half-closed and idle deadlines, shorter than stall
        h = hashlib.sha256(head)
        while True:
            d = s.recv(1 << 16)
            if not d:
                break
            h.update(d)
        s.close()
        self.assertEqual(h.digest(), digest(11, n))
        si, so = self.assert_clean_stop(p, host)
        for st in (si, so):
            self.assertEqual((st['halfClosedTimeouts'], st['idleTimeouts'], st['stalledTimeouts']), (0, 0, 0), st)

