#!/bin/bash
# enrollfail.sh <run-id>: assemble enrollfail.py (interop16.py's helpers + the staged-cutover main) and run it in a PRIVATE
# network namespace (loopback only) and a PRIVATE PID namespace, as uid 1000 in a nested user namespace (PostgreSQL refuses
# root). Run it inside ONE claude-test-queue allocation (1536: one indexer + one wasmtime instance at a time).
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
id=${1:?run-id}
[[ "$id" =~ ^[a-z0-9]{1,12}$ ]] || { echo "run-id: [a-z0-9]{1,12}"; exit 2; }
{ printf '#!/usr/bin/env python3\n"""enrollfail.py: GENERATED by enrollfail.sh from _base.py (interop16.py helpers) + main_enrollfail.py; see main_enrollfail.py."""\n'
  cat "$here/_base.py" "$here/main_enrollfail.py"; } > "$here/enrollfail.py"
sha256sum "$here/_base.py" "$here/main_enrollfail.py" "$here/enrollfail.py"
mkdir -p "$here/runs"
exec unshare -rn --pid --fork --kill-child --mount-proc sh -c \
  'ip link set lo up && exec unshare -U --map-user=1000 --map-group=1000 python3 -u -B "$0" "$1"' "$here/enrollfail.py" "$id"
