#!/bin/bash
# rollbackorder.sh <run-id>: assemble rollbackorder.py (interop16.py helpers + main_rollbackorder.py), extract the ORIGINAL
# cutover.py of commit 6fd7a929 (the negative control) and run it in PRIVATE network + PID namespaces as uid 1000 (PostgreSQL
# refuses root). Run it inside ONE claude-test-queue allocation (1536: two indexers + one wasmtime instance at a time).
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
id=${1:?run-id}
[[ "$id" =~ ^[a-z0-9]{1,12}$ ]] || { echo "run-id: [a-z0-9]{1,12}"; exit 2; }
{ printf '#!/usr/bin/env python3\n"""rollbackorder.py: GENERATED by rollbackorder.sh from _base.py (interop16.py helpers) + main_rollbackorder.py."""\n'
  cat "$here/_base.py" "$here/main_rollbackorder.py"; } > "$here/rollbackorder.py"
mkdir -p "$here/tmp" "$here/runs"
git -C "$here/.." show 6fd7a9299c53121142ab59d8ff9a7406c1f2b845:package/tools/cutover.py > "$here/tmp/cutover-6fd7a929.py"
sha256sum "$here/_base.py" "$here/main_rollbackorder.py" "$here/rollbackorder.py" "$here/tmp/cutover-6fd7a929.py" "$here/../package/tools/cutover.py"
export OLD_CUTOVER="$here/tmp/cutover-6fd7a929.py"
exec unshare -rn --pid --fork --kill-child --mount-proc sh -c \
  'ip link set lo up && exec unshare -U --map-user=1000 --map-group=1000 python3 -u -B "$0" "$1"' "$here/rollbackorder.py" "$id"
