#!/bin/bash
# shardloss.sh <run-id>: assemble shardloss.py (storage-write-release's interop16 helpers _base.py, read-only and pinned,
# + main_shardloss.py) and run it in PRIVATE network + PID namespaces as uid 1000. ONE claude-test-queue allocation (1536).
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
id=${1:?run-id}
[[ "$id" =~ ^[a-z0-9]{1,12}$ ]] || { echo "run-id: [a-z0-9]{1,12}"; exit 2; }
base="$here/../../storage-write-release/rehearsal/_base.py"
[ "$(sha256sum "$base" | cut -c1-64)" = bd92f094f88ee7bf0e005171ac5d26d6fdd3879ef3bf9c707271cd15fa361b6b ] || { echo "_base.py pin mismatch"; exit 2; }
{ printf '#!/usr/bin/env python3\n"""shardloss.py: GENERATED by shardloss.sh from storage-write-release/rehearsal/_base.py + main_shardloss.py."""\n'
  cat "$base" "$here/main_shardloss.py"; } > "$here/shardloss.py"
mkdir -p "$here/runs"
export SHARDLOSS_FIXED="$here/../artifacts/candidate-55888a41.wasm"
export SHARDLOSS_FIXED_SHA256=55888a41033c5c913f64adc7dc601d314cbe387b377445a23e5475643bea7918
sha256sum "$base" "$here/main_shardloss.py" "$here/shardloss.py" "$SHARDLOSS_FIXED"
exec unshare -rn --pid --fork --kill-child --mount-proc sh -c \
  'ip link set lo up && exec unshare -U --map-user=1000 --map-group=1000 python3 -u -B "$0" "$1"' "$here/shardloss.py" "$id"
