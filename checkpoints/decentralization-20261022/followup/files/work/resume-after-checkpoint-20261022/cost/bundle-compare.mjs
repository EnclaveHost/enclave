// READ-ONLY: rebuild the two shipped lease bundles IN MEMORY (write: false), once with the current
// network/lease-gas-owner.mjs and once with the pre-change copy (orig/lease-gas-owner.mjs) substituted, and compare
// each with the shipped bytes. Nothing in work/enclave is written. Options mirror scripts/build-*-lease-*.mjs.
import { createRequire } from "node:module";
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
const root = path.resolve(new URL("../../enclave", import.meta.url).pathname);
const { build } = createRequire(path.join(root, "package.json"))("esbuild");
const sha = (b) => createHash("sha256").update(b).digest("hex");
const owner = path.join(root, "network/lease-gas-owner.mjs");
const orig = fs.readFileSync(new URL("./orig/lease-gas-owner.mjs", import.meta.url), "utf8");
const swap = (useOrig) => ({ name: "owner-swap", setup(b) { if (useOrig) b.onLoad({ filter: /lease-gas-owner\.mjs$/ }, (a) => a.path === owner ? { contents: orig, loader: "js" } : undefined); } });
const canon = { name: "canonical-lease-client", setup(b) { b.onResolve({ filter: /^\.\/lease-executor-client\.mjs$/ }, (a) =>
  a.resolveDir === path.join(root, "network") ? { path: path.join(root, "client/lease-executor-client.mjs") } : undefined); } };
const targets = [
  { name: "windows", entry: "network/lease-gas-runtime.mjs", out: "windows/node/lease-gas-runtime.bundle.mjs", banner: "// Generated from shared network/lease-gas-runtime.mjs; do not edit.", plugins: [canon] },
  { name: "metal", entry: "network/lease-gas-conduit.mjs", out: "metal/guest/lease-gas-conduit.bundle.mjs", banner: "// Generated by scripts/build-metal-lease-gas.mjs from network/lease-gas-conduit.mjs; do not edit.", plugins: [] }];
const res = {};
for (const t of targets) {
  const shipped = fs.readFileSync(path.join(root, t.out));
  res[t.name] = { shipped: sha(shipped) };
  for (const useOrig of [true, false]) {
    const r = await build({ absWorkingDir: root, entryPoints: [t.entry], outfile: path.join(root, t.out), platform: "node", format: "esm", target: "node20",
      bundle: true, minify: true, write: false, metafile: true, banner: { js: t.banner }, plugins: [swap(useOrig), ...t.plugins] });
    const bytes = Buffer.from(r.outputFiles[0].contents);
    res[t.name][useOrig ? "withOrigOwner" : "withNewOwner"] = { sha256: sha(bytes), bytes: bytes.length, equalsShipped: bytes.equals(shipped) };
  }
}
console.log(JSON.stringify(res, null, 1));
// token-level diff of the metal bundle (orig vs new owner), when DIFF=1
if (process.env.DIFF) {
  for (const t of targets) {
    const outs = [];
    for (const useOrig of [true, false]) outs.push(Buffer.from((await build({ absWorkingDir: root, entryPoints: [t.entry], outfile: path.join(root, t.out), platform: "node", format: "esm",
      target: "node20", bundle: true, minify: true, write: false, banner: { js: t.banner }, plugins: [swap(useOrig), ...t.plugins] })).outputFiles[0].contents).toString("utf8"));
    const [a, b] = outs; const diffs = [];
    for (let i = 0; i < a.length && diffs.length < 12; i++) if (a[i] !== b[i]) { diffs.push({ at: i, orig: a.slice(i - 30, i + 30), now: b.slice(i - 30, i + 30) }); i += 60; }
    let n = 0; for (let i = 0; i < a.length; i++) if (a[i] !== b[i]) n++;
    console.log(t.name, "differing chars", n, JSON.stringify(diffs.slice(0, 6), null, 1));
  }
}
