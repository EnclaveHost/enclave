that maps an unadmitted executable, one whose member was renamed over after encoding (same bytes, new inode), and
one that never finished loading the set.

WHAT THIS DOES NOT ESTABLISH

  ONE app on ONE plane. Nothing here demonstrates isolation BETWEEN two apps on two planes, which is the
  requirement. The second-plane blocker stands unchanged: precondition 4's mechanism is unresolved (see
  HOST-CHANGE-PLAN.md), and no run is to be scored as isolation.

  THE COMPONENT IS NOT ADMITTED. What the runtime compiles and runs is /app.wasm, extracted from the bundle at
  BUILD time (build-plane-guest.sh). The admitted artifact is the bundle. Both are in the initrd the firmware
  verifies under step 2, so the component is inside the launch measurement - but the link between the admitted
  bundle and the executed component is the build, not admission. That is the next gap of the same shape; closing
  it means planeinit handing the runtime the component cut from the file it admitted.

  THE MAPS CHECK IS ONE READING AT LOAD. It sees what the loader mapped at start. A library opened later with
  dlopen would not be seen. None was observed for this command line on the host (LD_DEBUG=libs,files, one request
  served), which is an observation about this wasmtime build, not a guarantee.

  THE CHECK IS THE PLANE'S OWN WORD. planeinit performs it and prints it; the hardware does not attest it. It is
  worth relying on because planeinit is inside the initrd the launch measurement covers under step 2 and it fails
  closed (powers off) - the same standing as the VMPCK probe, and no stronger.

  THE FROZEN PAGES ARE A COPY. The SVSM hashes and freezes the STAGED copy of the set; the runtime executes the
  files in /rt. What ties them is that planeinit reads the same files it later starts, and that the maps check
  requires the executing file objects to be the ones it encoded (same inode). An in-place write to an /rt file
  between admission and start would need a writer inside the plane, and only measured code runs there; this is
  not enforced by hardware.

  THE LIBRARY LIST COMES FROM ldd ON THE BUILD HOST. The maps check is what guards it at runtime: a library the list
  missed would be an unadmitted executable mapping, and a listed one nothing loads would never be mapped - both stop
  the plane.

  THE STEP-2 FIXTURE WAS NOT RE-RUN. admitinit now stages the set as well (one meaning of ENCLAVE_RUNTIME_SHA256), and
  test-rtset check 13 shows its image carries the same set under the same digest, but verify-measured-boot.sh was
  not re-run on hardware. evidence/step2-measured-boot-2026-09-24.txt remains the record of the ELF-only fixture at
  its own revision.

  NOT INDEPENDENTLY REVIEWED.
