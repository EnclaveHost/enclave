#!/bin/sh
# Write the runtime-set evidence FROM a verify-runtime-set.sh run directory. Every quoted line is cut from a file in
# that directory, never from a terminal: good/ (verify-plane.sh), changed/ and missing/ (the negative controls),
# run.log (the harness's own scoring), test-rtset.out and svsm-unit-tests.out (the local tests at the same code).
#
#   usage: write-runtime-set-evidence.sh <workdir>
set -e
W=${1:?usage: write-runtime-set-evidence.sh <workdir>}
for f in run.log good/P.evidence changed/P.evidence missing/P.evidence test-rtset.out svsm-unit-tests.out; do
  [ -r "$W/$f" ] || { echo "no $W/$f - run verify-runtime-set.sh and the local tests into it first" >&2; exit 2; }
done
clean() { tr -d '\000' < "$1" | sed 's/\x1b\[[0-9;=?]*[A-Za-z]//g'; }
ev() { clean "$W/$1/P.evidence" | grep -ao "PLANE $2.*" | head -1 | sed 's/^/  /'; }
evall() { clean "$W/$1/P.evidence" | grep -ao "PLANE $2.*" | sed 's/^/  /'; }
svsm() { clean "$W/$1/P.serial" | grep -ao "SVSM appid: .*" | sed 's/^/  /'; }
hashes() { clean "$W/$1/P.debugcon" | grep -ao 'Hash comparison [a-z]* for "[a-z]*"' | sed 's/^/  /'; }
j() { python3 -c 'import json,sys
v=json.load(open(sys.argv[1]))
for k in sys.argv[2].split("."): v=v[k]
print(v)' "$W/$1/plane.manifest.json" "$2"; }
rtset_of() { sed -n 's/.*runtime set     \([0-9a-f]*\) .*/\1/p' "$W/$1/build-guest.txt"; }
passes() { grep -a "$1" "$W/run.log" | sed 's/^ *//; s/^/  /'; }

