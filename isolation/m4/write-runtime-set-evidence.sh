wasmtime ELF alone, so the interpreter, libc, libm and libgcc_s executed without the SVSM ever hashing them. Both
earlier evidence files (step2-measured-boot, plane-handshake-binding) say so, and stay scoped to that.

WHAT CHANGED. The runtime kind now admits ONE canonical encoding of every file in /rt (guest/rtset.h,
"enclave-runtime-set-v1": each member's name, length and bytes, in bytewise name order; a subdirectory, symlink or
any other non-file refuses the whole set). ENCLAVE_RUNTIME_SHA256 is sha256 of that encoding. The SVSM's code did
