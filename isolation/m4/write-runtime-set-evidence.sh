0x80001004 is E_DIGEST_MISMATCH, which appid.rs returns only after hashing the staged bytes and finding them unequal
to the compiled-in digest. The SVSM logged kind 0 (the bundle) and NO kind 1 in either negative: nothing of the set
was frozen, no whoami, no key registered, no document served; planeinit powered the domain off. The launch digests
