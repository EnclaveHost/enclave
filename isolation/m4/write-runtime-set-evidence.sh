are also copied with SHA256SUMS into $W/harness/.
Local tests re-run at $(cat "$W/local-test.commit" 2>/dev/null || echo "(unrecorded)"). One plane, plane 2. NOT independently reviewed: the reviewer is unavailable, and nothing
after 39b5a5e4 has been reviewed.

