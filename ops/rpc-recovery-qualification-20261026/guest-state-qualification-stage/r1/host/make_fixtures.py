#!/usr/bin/env python3
"""make_fixtures.py (guest-state-qualification-stage/r1; PREPARED, never run by Claude). HOST side, root, no network.
Writes tiny deterministic .tar.zst fixtures for Q2 (extract confinement of the REAL pinned base binary) plus fixtures.json
(sha256 of every fixture + the expected outcome). Requirements: Python >= 3.8 stdlib (tarfile) + the `zstd` CLI; it does NOT use
Python 3.14's compression.zstd, so the same file runs under the guest's 3.12 too. Fixtures are generated by root and then pinned by the
sha256 values this script prints/records -- nothing here is a pre-computed hash.

Every hostile fixture aims at the SCRATCH DECOY directory given by --decoy (an absolute guest path OUTSIDE the extract sandbox's
writable paths), never at data/. The guest runner (guest/q2_extract_confinement.py) creates that decoy with known bytes and requires it
byte-identical after every case.
"""
import argparse, hashlib, io, json, os, subprocess, sys, tarfile

MTIME = 1_700_000_000
GOOD = [('db/database.version', b'2'), ('db/lock', b'0123456789ab'), ('db/mdbx.dat', b'M' * 4096), ('db/mdbx.lck', b'L' * 512)]


def _ti(name, kind=tarfile.REGTYPE, size=0, linkname='', mode=0o644):
    t = tarfile.TarInfo(name); t.type = kind; t.size = size; t.linkname = linkname; t.mode = mode
    t.mtime = MTIME; t.uid = t.gid = 0; t.uname = t.gname = 'root'
    return t


def build(entries):
    """entries: list of (TarInfo, bytes|None). Raw names are written as given (no sanitising): that is the point."""
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode='w', format=tarfile.PAX_FORMAT) as tf:
        for ti, data in entries:
            tf.addfile(ti, io.BytesIO(data) if data is not None else None)
    return buf.getvalue()


def cases(decoy):
    decoy = decoy.rstrip('/')
    good = [(_ti(p, size=len(b)), b) for p, b in GOOD]
    d = lambda: [(_ti('db', tarfile.DIRTYPE, mode=0o755), None)]
    return {
        # positive control: exactly the declared shape (staging must equal it; nothing else touched)
        'good': (d() + good, 'extracted-exact'),
        # absolute path aimed at the decoy
        'abs-path': (d() + good + [(_ti(f'{decoy}/abs-target', size=4), b'EVIL')], 'refused-or-confined'),
        # parent traversal from the staging datadir (<scratch>/stage -> <scratch>/decoy)
        'traversal': (d() + good + [(_ti('../decoy/trav-target', size=4), b'EVIL')], 'refused-or-confined'),
        # symlink to the decoy, then a regular file written THROUGH it
        'symlink-write-through': (d() + good + [(_ti('db/escape', tarfile.SYMTYPE, linkname=decoy), None),
                                                (_ti('db/escape/through-target', size=4), b'EVIL')], 'refused-or-confined'),
        # relative symlink variant
        'symlink-relative': (d() + good + [(_ti('db/escape2', tarfile.SYMTYPE, linkname='../../decoy'), None),
                                           (_ti('db/escape2/through-target', size=4), b'EVIL')], 'refused-or-confined'),
        # hardlink to a decoy file (absolute and relative linknames)
        'hardlink-abs': (d() + good + [(_ti('db/hl', tarfile.LNKTYPE, linkname=f'{decoy}/victim'), None)], 'refused-or-confined'),
        'hardlink-rel': (d() + good + [(_ti('db/hl2', tarfile.LNKTYPE, linkname='../decoy/victim'), None)], 'refused-or-confined'),
        # an extra file beyond the declared outputs (must be refused by the exact-set check)
        'extra-file': (d() + good + [(_ti('db/extra.bin', size=1), b'x')], 'refused-or-confined'),
        # a device node (needs CAP_MKNOD; the sandbox has no capabilities)
        'device-node': (d() + good + [(_ti('db/dev', tarfile.CHRTYPE), None)], 'refused-or-confined'),
        # a file outside db/ inside the staging datadir (e.g. reth.toml): not part of the declared set
        'outside-db': (d() + good + [(_ti('reth.toml', size=5), b'evil\n')], 'refused-or-confined'),
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--out', required=True, help='new empty directory for the fixtures')
    ap.add_argument('--decoy', required=True, help='absolute GUEST path of the scratch decoy dir, e.g. /srv/enclave-base-holder/tmp/gsq-r1/<run>/decoy')
    ap.add_argument('--zstd', default='/usr/bin/zstd')
    a = ap.parse_args()
    nd = os.path.normpath(a.decoy)
    if not os.path.isabs(a.decoy) or nd != a.decoy.rstrip('/') or nd == '/srv/enclave-base-holder/data' or \
            nd.startswith('/srv/enclave-base-holder/data/') or not nd.startswith('/srv/enclave-base-holder/tmp/gsq-r1/'):
        sys.exit('--decoy must be a normalised absolute scratch path under /srv/enclave-base-holder/tmp/gsq-r1/, never the datadir')
    os.makedirs(a.out, mode=0o700, exist_ok=False)
    zver = subprocess.run([a.zstd, '--version'], capture_output=True, text=True, check=True).stdout.strip()
    rec = {'format': 'enclave-guest-qualification-fixtures/r1', 'decoy': a.decoy, 'zstd': zver, 'python': sys.version.split()[0],
           'goodOutputs': {p: {'size': len(b), 'sha256': hashlib.sha256(b).hexdigest()} for p, b in GOOD}, 'fixtures': {}}
    for name, (entries, expect) in cases(a.decoy).items():
        raw = build(entries)
        z = subprocess.run([a.zstd, '-q', '-19', '--no-progress', '-c'], input=raw, capture_output=True, check=True).stdout
        p = os.path.join(a.out, f'{name}.tar.zst')
        with open(p, 'xb') as f:
            f.write(z)
        rec['fixtures'][name] = {'file': f'{name}.tar.zst', 'sha256': hashlib.sha256(z).hexdigest(), 'size': len(z), 'expect': expect,
                                 'members': [e[0].name + (' -> ' + e[0].linkname if e[0].linkname else '') for e in entries]}
    with open(os.path.join(a.out, 'fixtures.json'), 'x') as f:
        json.dump(rec, f, indent=1, sort_keys=True); f.write('\n')
    print(json.dumps({k: v['sha256'] for k, v in rec['fixtures'].items()}, indent=1))


if __name__ == '__main__':
    main()
