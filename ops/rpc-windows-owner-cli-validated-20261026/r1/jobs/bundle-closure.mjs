// Bundle closure for the Windows candidate (windows-chain-authority-stage r3; run by the root job inside a tree, cwd = tree root).
// For each host-admission output: the SAME esbuild options as scripts/build-host-admission.mjs (copied exactly, plus metafile,
// which does not change the output bytes) -> {entry, file, committedSha256, generatedSha256, stale, inputs: {path: sha256}}.
// Nothing is written. Usage: node bundle-closure.mjs <out.json>
import { build } from "esbuild";
import fs from "node:fs";
import crypto from "node:crypto";
const sha = (b) => crypto.createHash("sha256").update(b).digest("hex");
const out = [];
for (const [entry, file] of [["network/host-admission-node.mjs", "windows/node/host-admission.bundle.mjs"], ["network/metal-host-policy.mjs", "metal/guest/host-policy.bundle.mjs"]]) {
  const r = await build({ entryPoints: [entry], outfile: file, write: false, bundle: true, platform: "node", format: "esm", target: "node20", minify: true,
    banner: { js: "// Generated by scripts/build-host-admission.mjs; edit " + entry + "." }, metafile: true });
  const bytes = Buffer.from(r.outputFiles[0].contents);
  const committed = fs.existsSync(file) ? fs.readFileSync(file) : null;
  const inputs = Object.fromEntries(Object.keys(r.metafile.inputs).sort().map((p) => [p, sha(fs.readFileSync(p))]));
  out.push({ entry, file, committedSha256: committed ? sha(committed) : null, generatedSha256: sha(bytes), stale: !committed || !committed.equals(bytes), inputs });
}
fs.writeFileSync(process.argv[2], JSON.stringify(out, null, 1) + "\n");
for (const o of out) console.log(`${o.file}: committed ${o.committedSha256?.slice(0, 16)} generated ${o.generatedSha256.slice(0, 16)} ${o.stale ? "STALE" : "current"} (${Object.keys(o.inputs).length} inputs)`);
