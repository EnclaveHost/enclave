def sha(b):
    return hashlib.sha256(b).hexdigest()


def die(m):
    sys.exit(f"generate_harness.py: {m}")


def apply(text, edits, what):
    new = text
    for a, b in edits:
        if new.count(a) != 1:
            die(f"{what}: anchor occurs {new.count(a)} times (expected 1): {a[:80]!r}")
        if a not in b and new.count(b) != 0:
            die(f"{what}: replacement text already present")
        new = new.replace(a, b)
    back = new
    for a, b in reversed(edits):
        if back.count(b) != 1:
            die(f"{what}: replacement occurs {back.count(b)} times: {b[:80]!r}")
        back = back.replace(b, a)
    if back != text:
        die(f"{what}: reversing the edits does not give back the pinned source exactly")
    return new


def main():
    pins = json.loads((HERE / "generated" / "HARNESS-GEN-PINS.json").read_text())["inputs"]
    if set(pins) != set(INPUTS):
        die(f"HARNESS-GEN-PINS.json must list exactly {sorted(INPUTS)}")
    src = {}
    for rel, want in pins.items():
        if not isinstance(want, str) or not re.fullmatch(r"[0-9a-f]{64}", want):
            die(f"{rel}: no root-filled sha256 (refusing)")
        b = (UF / rel).read_bytes()
        if sha(b) != want:
            die(f"{rel}: sha256 {sha(b)} != pinned {want} (refusing)")
        src[rel] = b
    for d in OUTDIRS:
        if (HERE / d).exists():
            die(f"{d}/ already exists; inspect or move it first (nothing is overwritten)")

    server = src[f"{B}/out/server.mjs"].decode("utf-8")
    if M in server:
        die(f"the source server already mentions {M}")
    new_server = apply(server, SERVER_EDITS, "server")
    if new_server.count(GUARD) != 1:
        die("the unchanged no-code-size-override refusal must remain exactly once")
    scanned = new_server.replace(GUARD, "")            # keep that refusal; scan every other byte
    for bad in ("--code-size", "disable-code-size", "pkill", "killall", "process.kill(-"):
        if bad in scanned:
            die(f"the derived server contains {bad!r}")
    for keep in ('"--chain-id", "8453", "--hardfork", "osaka"', '"--slots-in-an-epoch", "1"', 'if (req.headers.host !== here)',
                 "let dropFirstFundingOpen = true;", "maxSeconds must be 30..1800", 'owned.server.listen(port, "127.0.0.1"'):
        if new_server.count(keep) != 1:
            die(f"the derived server must keep {keep!r} exactly once")

    main_js = src[f"{B}/shell/main.mjs"].decode("utf-8")
    if M in main_js:
        die(f"the source shell already mentions {M}")
    fragment = src[FRAGMENT].decode("utf-8")
    main_edits = MAIN_EDITS_FIXED + [before('phase("pControls", ', fragment)]
    # the pControls anchor of the insertion must be resolved AFTER its own "funded" -> "execDone" edit: apply in two passes
    new_main = apply(main_js, MAIN_EDITS_FIXED, "shell/main.mjs")
    new_main = apply(new_main, [before('phase("pControls", ', fragment)], "shell/main.mjs (phases 12-16)")
    if apply(main_js, main_edits[:-1], "check") != new_main.replace(fragment, "", 1):
        die("inserting the phases changed something else")
    for phase in ("pExecFinal", "pExecLost", "pExecReload", "pExec502", "pExecSwitch"):
        if new_main.count(f'phase("{phase}", ') != 1:
            die(f"phase {phase} must be defined exactly once")

    build = src[f"{B}/build/build-harness.mjs"].decode("utf-8")
    new_build = apply(build, BUILD_EDITS, "build/build-harness.mjs")
    page = src[f"{B}/page/index.html"].decode("utf-8")
    new_page = apply(page, PAGE_EDITS, "page/index.html")

    outputs = {"out/server.mjs": new_server.encode("utf-8"), "shell/main.mjs": new_main.encode("utf-8"),
               "build/build-harness.mjs": new_build.encode("utf-8"), "page/index.html": new_page.encode("utf-8")}
    for rel, t in COPIES.items():
        outputs[t] = src[rel]
    for p, b in outputs.items():
        f = HERE / p
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_bytes(b)
    gen = {"schema": f"{M}-harness-generated/v1", "inputs": pins, "outputs": {p: sha(b) for p, b in sorted(outputs.items())},
           "edits": {"server": len(SERVER_EDITS), "shell": len(MAIN_EDITS_FIXED) + 1, "build": len(BUILD_EDITS), "page": len(PAGE_EDITS)}}
    (HERE / "out" / "GENERATED.json").write_text(json.dumps(gen, indent=2) + "\n")
    print(json.dumps(gen["outputs"], indent=2))


if __name__ == "__main__":
    main()
