def die(msg):
    sys.exit(f"generate.py: {msg}")


def sha(b):
    return hashlib.sha256(b).hexdigest()


def main():
    pins = json.loads((HERE / "generated" / "GENERATOR-PINS.json").read_text())["inputs"]
    if set(pins) != {SRC_REL}:
        die(f"GENERATOR-PINS.json must list exactly {SRC_REL}")
    want = pins[SRC_REL]
    if not isinstance(want, str) or not re.fullmatch(r"[0-9a-f]{64}", want):
        die(f"{SRC_REL}: no root-filled sha256 (refusing)")
    raw = (UF / SRC_REL).read_bytes()
    if sha(raw) != want:
        die(f"{SRC_REL}: sha256 {sha(raw)} != pinned {want} (refusing)")
    if OUT.exists():
        die("out/ already exists; inspect or move it first")
    text = raw.decode("utf-8")
    if "client-site-browser-r1" in text:
        die("the source server already mentions client-site-browser-r1")
    new = text
    for a, b in EDITS:
        n = new.count(a)
        if n != 1:
            die(f"anchor occurs {n} times (expected 1): {a[:70]!r}")
        if b.count(a) == 0 and new.count(b) != 0:
            die(f"replacement text already present: {b[:70]!r}")
        new = new.replace(a, b)
    back = new
    for a, b in reversed(EDITS):
        if back.count(b) != 1:
            die(f"replacement occurs {back.count(b)} times after editing: {b[:70]!r}")
        back = back.replace(b, a)
    if back != text:
        die("reversing the edits does not give back the pinned server exactly")
    guard = '  if (args.some((a) => /code-size|disable-code-size/.test(a))) fail("no code-size override");'
    if new.count(guard) != 1:
        die("the original Anvil size-override refusal is missing or repeated")
    checked = new.replace(guard, "")  # Preserve this exact refusal; scan every other byte.
    for bad in ("--code-size", "disable-code-size", "pkill", "killall", "process.kill(-"):
        if bad in checked:
            die(f"the derived server contains {bad!r}")
    OUT.mkdir()
    (OUT / "server.mjs").write_text(new)
    (OUT / "GENERATED.json").write_text(json.dumps({"schema": "client-site-browser-r1-generated/v1",
        "source": {SRC_REL: want}, "outputs": {"out/server.mjs": sha(new.encode("utf-8"))}, "edits": len(EDITS)}, indent=2) + "\n")
    print(f"out/server.mjs sha256 {sha(new.encode('utf-8'))} ({len(EDITS)} edits)")


if __name__ == "__main__":
    main()
