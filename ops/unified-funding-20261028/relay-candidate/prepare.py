#!/usr/bin/env python3
"""UNREVIEWED SOURCE (unified-funding relay-r1). Deterministic stage preparation. Writes ONLY inside this stage:

  generated/funding-abi.mjs        ABIs extracted from the compiled session-r1 artifacts (Grant tuple included)
  patched/relay/sessions.mjs       a PATCHED COPY of source/relay/sessions.mjs: marked, insert-only blocks
  patched/relay/funding-route.mjs  ./funding-route.mjs with its two stage-relative imports made drop-in
  patched/relay/funding-abi.mjs    copy of generated/funding-abi.mjs
  generated/PREPARE-MANIFEST.json  sha256 of every input and output

The original source is opened read-only and must hash to the pinned SHA-256; nothing outside this directory is
written. No network, no keys, no execution of anything but this script.

  python3 prepare.py          write the outputs
  python3 prepare.py --check  write nothing; exit 1 if any output is missing or differs from what would be written
"""
import hashlib
import json
import os
import sys

STAGE = os.path.dirname(os.path.realpath(__file__))
SOURCE_SESSIONS = os.path.join(STAGE, "..", "..", "..", "relay", "sessions.mjs")
SOURCE_SESSIONS_SHA256 = "457e86472adce2f1fdd2dfa82759578a56f7d72f0c5e5ee18e53999a26d0682d"
OUT = os.path.join(STAGE, "..", "session-candidate", "out")
ARTIFACTS = {
    "vault": os.path.join(OUT, "FundingSessionVault.sol", "FundingSessionVault.json"),
    "factory": os.path.join(OUT, "FundingSessionVault.sol", "FundingSessionVaultFactory.json"),
    "vaultLib": os.path.join(OUT, "FundingSessionVault.sol", "FundingSessionVaultLib.json"),
    "gasLib": os.path.join(OUT, "FundingGasLib.sol", "FundingGasLib.json"),
    "ledger": os.path.join(OUT, "FundingSessionVault.sol", "ISVLedger.json"),
    "adapter": os.path.join(OUT, "LeaseGasDexAdapter.sol", "LeaseGasDexAdapter.json"),
}
# the successor build the root qualified: runs 1, via-IR, osaka, no metadata hash
EXPECTED_SETTINGS = {"runs": 1, "viaIR": True, "evmVersion": "osaka", "bytecodeHash": "none"}
ROUTE_SRC = os.path.join(STAGE, "funding-route.mjs")

HEADER = (
    "// >>> funding-r1 PATCHED COPY generated by relay-r1/prepare.py from source/relay/sessions.mjs (sha256\n"
    "// " + SOURCE_SESSIONS_SHA256 + "). Every change is a marked insert-only block like this one.\n"
    "// <<< funding-r1\n"
)

# (anchor that must occur EXACTLY once, lines inserted right after it). Insert-only: deleting every marked block
# reproduces the original byte for byte (test/prepare.test.mjs proves it).
HUNKS = [
    (
        'import { verifyQuote, parseSnpReport, provenSnpChip, seedCertChain } from "./snp-verify.mjs";\n',
        '// >>> funding-r1 (additive successor funding routes; inert unless configured)\n'
        'import { createFundingRoute, fundingManifestFromEnv } from "./funding-route.mjs";\n'
        '// <<< funding-r1\n',
    ),
    (
        '  if (o.attestor) log(att.address ? `attest: on, EnclaveKeyAttestations ${att.address}` : `attest: off (${att.why})`);\n',
        '  // >>> funding-r1 (additive, opt-in). o.funding absent => every /funding/* route answers 503 funding_disabled.\n'
        '  // ownerManagement stays false: this host serves no reviewed successor owner route, so /funding/open is refused.\n'
        '  // o.fundingQuotePolicy ({ fee, accept }) must come from reviewed host code; without it no price is offered.\n'
        '  const funding = createFundingRoute({ manifest: o.funding ?? null, quotePolicy: o.fundingQuotePolicy ?? null,\n'
        '    ownerManagement: false, pc, relayer: account.address, store, log, now,\n'
        '    simulateAndSend: (req) => simulateAndSend(req) });\n'
        '  // <<< funding-r1\n',
    ),
    (
        '  async function route(method, path, body, ctx) {\n',
        '    // >>> funding-r1\n'
        '    if (path === "/funding" || path.startsWith("/funding/")) return funding.route(method, path, body, ctx);\n'
        '    // <<< funding-r1\n',
    ),
    (
        '    attestor: attestorEnv(),\n',
        '    // >>> funding-r1\n'
        '    funding: fundingManifestFromEnv(process.env),\n'
        '    // <<< funding-r1\n',
    ),
]

ROUTE_REWRITES = [
    ('from "viem";', 'from "viem";'),
    ('from "./generated/funding-abi.mjs";', 'from "./funding-abi.mjs";'),
]


def die(m):
    sys.stderr.write(f"prepare.py: {m}\n")
    sys.exit(1)


def sha256(b):
    return hashlib.sha256(b).hexdigest()


def read(path):
    with open(path, "rb") as f:
        return f.read()


def inside_stage(path):
    p = os.path.realpath(path)
    if os.path.commonpath([p, STAGE]) != STAGE:
        die(f"refusing to write outside the stage: {p}")
    return p


def canon_type(p):
    t = p["type"]
    if t.startswith("tuple"):
        return "(" + ",".join(canon_type(c) for c in p["components"]) + ")" + t[len("tuple"):]
    return t


def signature(item):
    return item["type"] + ":" + item["name"] + "(" + ",".join(canon_type(i) for i in item.get("inputs", [])) + ")"


def artifact(name):
    raw = read(ARTIFACTS[name])
    try:
        j = json.loads(raw)
    except ValueError as e:
        die(f"{ARTIFACTS[name]} is not JSON: {e}")
    if not isinstance(j.get("abi"), list) or not j["abi"]:
        die(f"{ARTIFACTS[name]} has no abi")
    return j, sha256(raw)


def check_settings(j, label):
    s = (j.get("metadata") or {}).get("settings") or {}
    got = {
        "runs": (s.get("optimizer") or {}).get("runs"),
        "viaIR": s.get("viaIR"),
        "evmVersion": s.get("evmVersion"),
        "bytecodeHash": (s.get("metadata") or {}).get("bytecodeHash"),
    }
    if got != EXPECTED_SETTINGS:
        die(f"{label} artifact was not built with {EXPECTED_SETTINGS} (got {got})")


def build():
    src = read(os.path.realpath(SOURCE_SESSIONS))
    if sha256(src) != SOURCE_SESSIONS_SHA256:
        die(f"source/relay/sessions.mjs sha256 {sha256(src)} is not the pinned {SOURCE_SESSIONS_SHA256}")

    arts = {k: artifact(k) for k in ARTIFACTS}
    for k in ("vault", "factory", "gasLib", "vaultLib"):
        check_settings(arts[k][0], k)

    vault_abi = list(arts["vault"][0]["abi"])
    seen = {signature(x) for x in vault_abi if x["type"] in ("event", "error")}
    # linked-library events/errors surface at the VAULT's address (DELEGATECALL) but are not in its artifact ABI
    for lib in ("gasLib", "vaultLib"):
        for x in arts[lib][0]["abi"]:
            if x["type"] in ("event", "error") and signature(x) not in seen:
                seen.add(signature(x))
                vault_abi.append(x)
    names = {x.get("name") for x in vault_abi}
    for need in ("execute", "sessionOf", "gasPolicyOf", "gasAdapter", "legacyFactory", "factory", "SessionOp",
                 "GasFunded", "SessionOpened"):
        if need not in names:
            die(f"the merged FundingSessionVault ABI lacks {need}")
    factory_abi = arts["factory"][0]["abi"]
    open_for = [x for x in factory_abi if x.get("type") == "function" and x.get("name") == "openFor"]
    if len(open_for) != 1:
        die("FundingSessionVaultFactory has no single openFor")
    grant = [c["name"] for c in open_for[0]["inputs"][1]["components"]]
    for need in ("maxGasUsdcPerOp", "maxUsdcPerEth6", "maxEthPerOp"):
        if need not in grant:
            die(f"the artifact Grant tuple lacks {need}")
    ledger_abi = [x for x in arts["ledger"][0]["abi"] if x.get("type") == "function" and x.get("name") == "get"]
    if len(ledger_abi) != 1:
        die("ISVLedger has no single get")

    rel = lambda p: os.path.relpath(os.path.realpath(p), STAGE)
    header = "// GENERATED by relay-r1/prepare.py from the compiled session-r1 artifacts. Do not edit.\n"
    for k in sorted(ARTIFACTS):
        header += f"// {rel(ARTIFACTS[k])} sha256 {arts[k][1]}\n"
    dump = lambda v: json.dumps(v, indent=2, ensure_ascii=False)
    abi_js = (header
              + "// FundingSessionVault ABI + the events/errors of its linked libraries (FundingGasLib, FundingSessionVaultLib)\n"
              + f"export const fundingSessionVaultAbi = {dump(vault_abi)};\n\n"
              + f"export const fundingSessionVaultFactoryAbi = {dump(factory_abi)};\n\n"
              + f"export const leaseGasDexAdapterAbi = {dump(arts['adapter'][0]['abi'])};\n\n"
              + f"export const fundingLedgerAbi = {dump(ledger_abi)};\n").encode()

    text = src.decode()
    for anchor, block in HUNKS:
        n = text.count(anchor)
        if n != 1:
            die(f"anchor occurs {n} times (must be exactly once): {anchor.strip()[:80]}")
        text = text.replace(anchor, anchor + block, 1)
    patched = (HEADER + text).encode()

    route = read(ROUTE_SRC).decode()
    for a, b in ROUTE_REWRITES:
        n = route.count(a)
        if n != 1:
            die(f"funding-route.mjs import occurs {n} times (must be exactly once): {a}")
        route = route.replace(a, b, 1)
    route_out = route.encode()

    outputs = {
        "generated/funding-abi.mjs": abi_js,
        "patched/relay/sessions.mjs": patched,
        "patched/relay/funding-route.mjs": route_out,
        "patched/relay/funding-abi.mjs": abi_js,
    }
    manifest = {
        "source": {"relay/sessions.mjs": SOURCE_SESSIONS_SHA256},
        "artifacts": {rel(ARTIFACTS[k]): arts[k][1] for k in sorted(ARTIFACTS)},
        "inputs": {"funding-route.mjs": sha256(read(ROUTE_SRC))},
        "outputs": {k: sha256(v) for k, v in sorted(outputs.items())},
        "settings": EXPECTED_SETTINGS,
    }
    outputs["generated/PREPARE-MANIFEST.json"] = (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode()
    return outputs


def main():
    check = "--check" in sys.argv[1:]
    outputs = build()
    stale = []
    for rel_path, data in outputs.items():
        path = inside_stage(os.path.join(STAGE, rel_path))
        if check:
            if not os.path.exists(path) or read(path) != data:
                stale.append(rel_path)
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        tmp = path + ".tmp"
        with open(tmp, "wb") as f:
            f.write(data)
        os.replace(tmp, path)
        print(f"wrote {rel_path} sha256 {sha256(data)}")
    if check:
        if stale:
            die("outputs missing or stale: " + ", ".join(stale))
        print("prepare.py --check: all outputs current")


if __name__ == "__main__":
    main()
