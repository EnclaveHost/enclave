def die(msg):
    sys.stderr.write("prepare.py: " + msg + "\n")
    sys.exit(1)


def main(argv):
    original = DEFAULT_ORIGINAL
    check = False
    i = 0
    while i < len(argv):
        if argv[i] == "--original":
            i += 1
            original = argv[i]
        elif argv[i] == "--check":
            check = True
        else:
            die("unknown argument " + argv[i])
        i += 1

    with open(original, "rb") as f:
        raw = f.read()
    got = hashlib.sha256(raw).hexdigest()
    if got != ORIGINAL_SHA256:
        die("original %s has sha256 %s, expected %s" % (original, got, ORIGINAL_SHA256))
    src = raw.decode("utf-8")

    src, n = RENAME_RE.subn(lambda m: "Funding" + m.group(0), src)
    if n != RENAME_COUNT:
        die("rename matched %d, expected %d" % (n, RENAME_COUNT))

    for label, old, new, count in EDITS:
        c = src.count(old)
        if c != count:
            die("edit %s: anchor occurs %d times, expected %d" % (label, c, count))
        src = src.replace(old, new)

    for pat in FORBIDDEN:
        if re.search(pat, src):
            die("forbidden pattern survived: " + pat)
    for needle, count in REQUIRED.items():
        c = src.count(needle)
        if c != count:
            die("required %r occurs %d times, expected %d" % (needle, c, count))

    out = src.encode("utf-8")
    print("original sha256 %s OK" % got)
    print("output   sha256 %s (%d bytes, %d edits + rename x%d)" % (hashlib.sha256(out).hexdigest(), len(out),
                                                                   len(EDITS), RENAME_COUNT))
    if check:
        return
    if os.path.exists(OUT):
        with open(OUT, "rb") as f:
            head = f.read(200).decode("utf-8", "replace")
        if BANNER not in head:
            die(OUT + " exists and is not a generated file; refusing to overwrite")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "wb") as f:
        f.write(out)
    print("wrote " + OUT)


if __name__ == "__main__":
    main(sys.argv[1:])
