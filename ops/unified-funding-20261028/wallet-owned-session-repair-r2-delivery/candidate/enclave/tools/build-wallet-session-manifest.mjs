// tools/build-wallet-session-manifest.mjs -- SOURCE ONLY (wallet-owned-session-repair-r2): never run by its author.
// Root runs it AFTER a qualified compile (size + tests) of exactly the reviewed source:
//   node tools/build-wallet-session-manifest.mjs <forge out dir> > relay/wallet-session-protocol.mjs
// Reads the forge artifacts of WalletSessionVaultFactory, WalletSessionVault, WalletSessionProfile and SessionVaultLib
// (deployedBytecode.object / immutableReferences / linkReferences + ast for immutable names) and emits the manifest the
// relay and hosts verify deployed code against (relay/wallet-session-manifest.mjs). It never fabricates bytes: every
// masked range is one solc itself reports; any missing artifact, AST name, unexpected immutable or library prefix FAILS.
import fs from "node:fs";
import path from "node:path";
import { keccak256 } from "viem";
import { validateManifest, MANIFEST_FORMAT, REQUIRED } from "../relay/wallet-session-manifest.mjs";
import { useViem } from "../relay/wallet-session-policy.mjs";
import * as viem from "viem";
useViem(viem);

const out = process.argv[2];
if (!out) { console.error("usage: build-wallet-session-manifest.mjs <forge out dir>"); process.exit(2); }
const SRC = { factory: ["WalletSessionVault.sol", "WalletSessionVaultFactory"], vault: ["WalletSessionVault.sol", "WalletSessionVault"],
  profile: ["WalletSessionProfile.sol", "WalletSessionProfile"], library: ["SessionVault.sol", "SessionVaultLib"] };

function namesById(ast) {
  const m = new Map();
  (function walk(n) { if (!n || typeof n !== "object") return; if (n.nodeType === "VariableDeclaration" && n.id != null) m.set(String(n.id), n.name);
    for (const v of Object.values(n)) if (Array.isArray(v)) v.forEach(walk); else if (v && typeof v === "object") walk(v); })(ast);
  return m;
}

const artifacts = {}, provenance = {};
for (const [name, [file, contract]] of Object.entries(SRC)) {
  const p = path.join(out, file, `${contract}.json`);
  const j = JSON.parse(fs.readFileSync(p, "utf8"));
  const d = j.deployedBytecode;
  if (!d?.object || !j.ast) throw new Error(`${p}: deployedBytecode/ast missing (build with ast output)`);
  let hex = String(d.object).replace(/^0x/, "");
  const links = {};
  for (const [, libs] of Object.entries(d.linkReferences || {})) for (const [lib, refs] of Object.entries(libs)) {
    links[lib] = refs.map((r) => [r.start, r.length]);
    for (const r of refs) hex = hex.slice(0, r.start * 2) + "00".repeat(r.length) + hex.slice((r.start + r.length) * 2);
  }
  if (/__\$/.test(hex)) throw new Error(`${contract}: unresolved link placeholder outside linkReferences`);
  const names = namesById(j.ast), immutables = {};
  for (const [astId, refs] of Object.entries(d.immutableReferences || {})) {
    const n = names.get(String(astId));
    if (!n) throw new Error(`${contract}: immutable ${astId} has no AST name`);
    immutables[n] = refs.map((r) => [r.start, r.length]);
  }
  for (const k of REQUIRED[name].immutables) if (!immutables[k]) throw new Error(`${contract}: immutable ${k} missing`);
  const self = [];
  if (name === "library") {   // solc library call guard: PUSH20 <own address> ADDRESS EQ, address zero in the artifact
    if (!hex.startsWith("73" + "00".repeat(20) + "3014")) throw new Error("SessionVaultLib: unexpected library prefix");
    self.push([1, 20]);
  }
  const code = "0x" + hex;
  artifacts[name] = { codeLength: hex.length / 2, maskedHash: keccak256(code).toLowerCase(), immutables, links, ...(self.length ? { self } : {}) };
  provenance[name] = { artifact: path.relative(out, p), sha256: viem.sha256(viem.toBytes(fs.readFileSync(p, "utf8"))) };
}
const manifest = { format: MANIFEST_FORMAT, protocol: keccak256(new TextEncoder().encode("enclave.wallet-session.v1")).toLowerCase(), artifacts };
validateManifest(manifest);   // the same bounds/overlap checks the consumers apply
process.stdout.write(`// GENERATED by tools/build-wallet-session-manifest.mjs - do not edit. Inputs: ${JSON.stringify(provenance)}\n`
  + `export const WALLET_SESSION_PROTOCOL_MANIFEST = ${JSON.stringify(manifest, null, 1)};\n`);
