// Builds network/attested-guest-verify.bundle.mjs: the IMAGE lineage's exact guest verification code for the exit/provider
// side. The attested chain verifier image is built from the control lineage (metal/guest/measured-control.mjs with the bound
// chainVerifier member, metal/measured-control-verify.mjs, metal/guest/chain-verifier.mjs); a caller that verifies such a
// guest must canonicalize its config and parse its statement with THAT code, not with an older copy. So it is bundled, from
// an exact export of the image commit, and pinned here: the manifest names the commit, every input's sha256 and the bundle's.
// Dependencies (viem) resolve from THIS repository's node_modules (the route lineage's lock), never from the image tree.
//   node scripts/build-attested-guest-verify.mjs <image tree> <image commit>            write bundle + manifest
//   node scripts/build-attested-guest-verify.mjs <image tree> <image commit> --check    refuse unless both are current
// test/fixtures/attested-guest-image.bundle.mjs (same build, the guest-side helpers) serves the tests' guest stand-in only.
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const [tree, commit] = process.argv.slice(2).filter((a) => !a.startsWith('--')), check = process.argv.includes('--check');
if (!tree || !/^[0-9a-f]{9,40}$/.test(String(commit))) { console.error('usage: build-attested-guest-verify.mjs <image tree> <image commit> [--check]'); process.exit(2); }
const sha = (b) => createHash('sha256').update(b).digest('hex');
const OUT = {
  verify: { file: 'network/attested-guest-verify.bundle.mjs', exports: {
    'metal/measured-control-verify.mjs': ['verifyMeasuredControl'],
    'metal/guest/measured-control.mjs': ['canonicalDirectConfig', 'configDigest', 'hostDataHex', 'CHAIN_VERIFIER_ROUTE', 'CHAIN_VERIFIER_READ_METHODS', 'MAX_VERIFIER_ANSWER_BYTES'] } },
  guest: { file: 'test/fixtures/attested-guest-image.bundle.mjs', exports: {
    'metal/guest/measured-control.mjs': ['CONFIG_FORMAT', 'GUEST_PATHS', 'canonicalDirectConfig', 'configDigest', 'hostDataHex', 'mintControlKeys', 'controlStatement', 'parseStatement',
      'createControlFront', 'planDirectBoot', 'addressOfPublicKey', 'jwkThumbprint', 'CHAIN_VERIFIER_ROUTE', 'JSONRPC_FILTER', 'MAX_VERIFIER_REQUEST_BYTES', 'MAX_VERIFIER_ANSWER_BYTES'],
    'metal/guest/chain-verifier.mjs': ['checkChainVerifier', 'REFUSING_VERIFIER'] } },
};
let stale = false;
for (const [name, o] of Object.entries(OUT)) {
  const entry = Object.entries(o.exports).map(([f, names]) => `export { ${names.join(', ')} } from ${JSON.stringify(path.resolve(tree, f))};`).join('\n') + '\n';
  // absWorkingDir = THIS repository: dependency module keys are always node_modules/... whatever the image tree's location
  const r = await build({ absWorkingDir: REPO, stdin: { contents: entry, resolveDir: path.resolve(tree), loader: 'js' }, bundle: true, platform: 'node', format: 'esm', target: 'node22',
    // whitespace-minified: no per-module path comments, so the bytes do not depend on where the image tree was exported
    write: false, metafile: true, legalComments: 'none', minifyWhitespace: true, nodePaths: [path.join(REPO, 'node_modules')], logLevel: 'silent',
    banner: { js: `// Generated by scripts/build-attested-guest-verify.mjs from image commit ${commit}; do not edit.\nimport {createRequire as __agvCreateRequire} from "node:module"; const require=__agvCreateRequire(import.meta.url);` } });
  const bytes = Buffer.from(r.outputFiles[0].contents);
  const inputs = {};
  for (const rel of Object.keys(r.metafile.inputs).sort()) {
    if (rel === '<stdin>') continue;
    const abs = path.resolve(REPO, rel), norm = rel.includes('node_modules/') ? 'node_modules/' + rel.split('node_modules/').pop() : path.relative(path.resolve(tree), abs);
    inputs[norm] = sha(fs.readFileSync(abs));
  }
  const manifest = JSON.stringify({ format: 'enclave-attested-guest-verify/v1', bundle: name, imageCommit: commit, bundleSha256: sha(bytes), inputs }, null, 1) + '\n';
  const file = path.join(REPO, o.file), mfile = file + '.manifest.json';
  if (check) {
    const ok = fs.existsSync(file) && fs.readFileSync(file).equals(bytes) && fs.existsSync(mfile) && fs.readFileSync(mfile, 'utf8') === manifest;
    console.log(`${o.file}: ${ok ? 'current' : 'STALE'} (${sha(bytes)})`); if (!ok) stale = true;
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, bytes); fs.writeFileSync(mfile, manifest);
    console.log(`${o.file} ${sha(bytes)} (${Object.keys(inputs).length} inputs)`);
  }
}
if (stale) process.exit(1);
