// Build the Enclave host-service packages (network/host-services/roles.mjs; work/hosted-service-placement): one
// dependency-free bundle per role, with the same esbuild options as the bundles the fleet already runs (network/build.mjs:
// enclave-directory.mjs), and a package manifest naming the bundle's sha256, every input's sha256, the role's runtime,
// state, secrets, cold-start dependencies and service-index kind. An operator pins the MANIFEST digest; the runner
// (network/host-services/runner.mjs) refuses any other bytes. --check: refuse stale bundles or manifests.
//   node scripts/build-host-service-packages.mjs [--check]
import { build } from 'esbuild';
import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import os from 'node:os';
import { ROLES, PACKAGE_FORMAT } from '../network/host-services/roles.mjs';
import { lockedInputs } from './locked-inputs.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'network/host-services/packages');
const args = process.argv.slice(2);
if (args.length && !(args.length === 1 && args[0] === '--check')) throw new Error('usage: build-host-service-packages.mjs [--check]');
const check = args.includes('--check');
const sha = (b) => createHash('sha256').update(b).digest('hex');
const CHAIN_READER = new Set(['custody/v2/quorum.mjs']);
await fs.mkdir(out, { recursive: true });
const summary = [], lockfiles = {};
// relay/network-runtime.bundle.mjs (gitignored, built by relay/build-network.mjs) is an INPUT of the roles that bundle the
// relay's DNS: rebuilt here into a scratch directory and compared byte for byte, its own npm inputs locked the same way
const RUNTIME_BUNDLE = 'relay/network-runtime.bundle.mjs';
let runtimeChecked = null;
const currentRuntimeBundle = () => (runtimeChecked ||= (async () => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'runtime-bundle-check-'));
  try {
    const file = path.join(dir, 'network-runtime.bundle.mjs');
    execFileSync(process.execPath, [path.join(root, 'relay/build-network.mjs'), file], { cwd: root, stdio: ['ignore', 'ignore', 'pipe'] });
    const have = await fs.readFile(path.join(root, RUNTIME_BUNDLE)).catch(() => null);
    if (!have || !have.equals(await fs.readFile(file))) throw new Error(`${RUNTIME_BUNDLE} is ${have ? 'stale' : 'missing'}: run node relay/build-network.mjs first`);
    const locked = lockedInputs(root, JSON.parse(await fs.readFile(file + '.manifest.json', 'utf8')).inputs);
    for (const [f, d] of Object.entries(locked.lockfiles)) lockfiles[f] = d;
  } finally { await fs.rm(dir, { recursive: true, force: true }); }
})());
for (const [role, r] of Object.entries(ROLES)) {
  const result = await build({ absWorkingDir: root, entryPoints: [r.bundleEntry || r.entry], outfile: path.join(out, `${role}.mjs`), write: false, metafile: true,
    bundle: true, platform: 'node', format: 'esm', target: 'node22', legalComments: 'none',
    // the banner's names are opaque to esbuild, so they must not collide with any bundled module's top-level import
    // (relay/network-runtime.bundle.mjs, itself a bundle, imports createRequire as bundleRequire)
    banner: { js: `// Generated by scripts/build-host-service-packages.mjs from ${r.entry} (role ${role}); do not edit.\nimport {createRequire as __enclaveHostRoleCreateRequire} from "node:module"; const require=__enclaveHostRoleCreateRequire(import.meta.url);` } });
  const bytes = Buffer.from(result.outputFiles[0].contents);
  // inside one bundle every module's import.meta.url is the bundle's: a library's "am I the main script?" check would fire
  // and run that library's CLI. Only the role's own entry check may be present, unless the role is bundled behind the
  // argv guard (r.bundleEntry: network/host-services/argv-guard.mjs makes every such check false).
  // the bundle must at least parse (a duplicate top-level declaration is a SyntaxError only node reports)
  const probe = path.join(os.tmpdir(), `host-role-${role}-${process.pid}.mjs`);
  try { await fs.writeFile(probe, bytes); execFileSync(process.execPath, ['--check', probe], { stdio: ['ignore', 'ignore', 'pipe'] }); }
  catch (e) { throw new Error(`${role}: the bundle does not parse: ${String(e.stderr || e.message).split('\n').filter(Boolean).slice(0, 6).join(' | ')}`); }
  finally { await fs.rm(probe, { force: true }); }
  const mainChecks = (bytes.toString('utf8').match(/process\.argv\[1\]\s*&&[^\n]{0,200}import\.meta\.url/g) || []).length;
  if (!r.bundleEntry && mainChecks > 1) throw new Error(`${role}: ${mainChecks} bundled "main module" checks; a bundled library's CLI would run inside the role (bundle it behind network/host-services/argv-guard.mjs)`);
  // pinned dependencies: every npm input exactly as the committed lockfiles pin it, and every GENERATED input (the gitignored
  // relay/network-runtime.bundle.mjs) exactly what this tree builds - otherwise the package is not reproducible from the commit
  const locked = lockedInputs(root, Object.keys(result.metafile.inputs));
  for (const [f, d] of Object.entries(locked.lockfiles)) lockfiles[f] = d;
  if (Object.keys(result.metafile.inputs).some((f) => f.split(path.sep).join('/') === RUNTIME_BUNDLE)) await currentRuntimeBundle();
  const inputs = {};
  for (const rel of Object.keys(result.metafile.inputs).sort()) {
    const normalized = rel.includes('node_modules/') ? 'node_modules/' + rel.split('node_modules/').pop() : rel;
    const digest = sha(await fs.readFile(path.resolve(root, rel)));
    if (inputs[normalized] && inputs[normalized] !== digest) throw new Error(`${role}: ambiguous bundle input ${normalized}`);
    inputs[normalized] = digest;
  }
  // what the bundle could reach that a public, secret-free, cold-startable role must never need
  // (custody/v2/quorum.mjs is the RPC majority-agreement reader - no key, no secret, no custody state - that the policy
  // mirror's fresh-block checks use through host-policy-runtime.mjs quorumSnapshot; it is the only custody/ path allowed)
  const forbidden = Object.keys(inputs).filter((f) => !CHAIN_READER.has(f) && /(^|\/)(custody|lease-relay-service|lease-gas-runtime|storage\/|sdk\/storage|secrets?-release|shield-secrets)/.test(f));
  if (forbidden.length) throw new Error(`${role}: the bundle reaches modules a host-service role must not depend on: ${forbidden.join(', ')}`);
  const manifest = JSON.stringify({ format: PACKAGE_FORMAT, role, entry: r.entry, ...(r.bundleEntry ? { bundleEntry: r.bundleEntry } : {}), bundle: `${role}.mjs`, bundleSha256: sha(bytes), bytes: bytes.length,
    runtime: r.runtime, kind: r.kind, serves: r.serves, state: r.state, secrets: r.secrets, cold: r.cold, notCold: r.notCold,
    builder: 'scripts/build-host-service-packages.mjs', inputs }, null, 2) + '\n';
  const files = [[`${role}.mjs`, bytes], [`${role}.package.json`, Buffer.from(manifest)]];
  for (const [name, content] of files) {
    const file = path.join(out, name);
    if (check) {
      const have = await fs.readFile(file).catch(() => null);
      if (!have || !have.equals(content)) throw new Error(`${name} is stale; run node scripts/build-host-service-packages.mjs`);
    } else await fs.writeFile(file, content);
  }
  summary.push(`${role}: bundle ${bytes.length} bytes sha256:${sha(bytes).slice(0, 16)}…, manifest sha256:${sha(Buffer.from(manifest))}, ${Object.keys(inputs).length} inputs`);
}
summary.push('npm inputs locked by: ' + Object.entries(lockfiles).sort().map(([f, d]) => `${f} sha256:${d}`).join(', '));
console.log(summary.join('\n') + (check ? '\n(verified current)' : ''));
