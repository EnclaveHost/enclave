#!/usr/bin/env python3
"""Regenerate the public native-startup vector with the independent V8 reference."""
import base64
import importlib.util
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
source = root / 'isolation/contract/catalog/desktop_reference.py'
spec = importlib.util.spec_from_file_location('desktop_reference', source)
reference = importlib.util.module_from_spec(spec)
spec.loader.exec_module(reference)
vectors = json.loads((source.parent / 'desktop_vectors.json').read_text())
record = next(v['record'] for v in vectors['ok'] if v['name'] == 'baseline')
config = json.loads(base64.b64decode(record['configBase64']))
config['egress'] = 'public-web'
record['configBase64'] = base64.b64encode(json.dumps(config, separators=(',', ':')).encode()).decode()
_, mapping = reference.derive(record, bytes.fromhex(vectors['component_hex']))
fixture = {'provenance': 'Synthetic public startup vector; generated by test/helpers/native-startup-fixture.py using the independent Python V8 reference.',
           'record': record, 'mapping': mapping, 'component_hex': vectors['component_hex']}
print(json.dumps(fixture, indent=2))
